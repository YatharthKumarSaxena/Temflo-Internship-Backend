// Pin code validation - major Indian cities and their pin codes
const pinCodeValidation = {
  // This is a simplified validation - in production, you'd want a comprehensive database
  isValidPinCode: function (pinCode) {
    // Basic Indian pin code format: 6 digits, first digit 1-9
    const pinRegex = /^[1-9][0-9]{5}$/;
    return pinRegex.test(pinCode);
  },

  getStateFromPinCode: function (pinCode) {
    // Simplified mapping for now
    const firstDigit = pinCode.charAt(0);
    const pinToStateMapping = {
      1: 'Delhi',
      2: 'Haryana',
      3: 'Punjab',
      4: 'Chandigarh',
      5: 'Uttarakhand',
      6: 'Himachal Pradesh',
      7: 'Jammu and Kashmir',
      8: 'Rajasthan',
      9: 'Uttar Pradesh',
    };
    return pinToStateMapping[firstDigit] || 'Unknown';
  },
};

